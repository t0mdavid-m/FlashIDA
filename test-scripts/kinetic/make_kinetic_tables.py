"""Generate FlashIDA/test-data/kinetic/*.tsv from the study's corrected table with the vendored pipeline (ADR-0047 d.10).

Run (host, Git Bash):
  uv run --with numpy --with matplotlib python -I FlashIDA/test-scripts/kinetic/make_kinetic_tables.py \
      "C:/FLASHIda/Measurements/MS2_Characterization/analysis/matched-share-regret-prediction/stabilized_HCD_corrected.tsv" \
      FlashIDA/test-data/kinetic

Reads only that table. Writes, each with a two-line '#' provenance header:
  sweep_shares.tsv      protein dataset charge sweep ce precursor_share reading          (108 sweeps x CE 1..50)
  kinetic_expected.tsv  protein dataset charge sweep offset n_points p0 ce_max_s width sse k2 ce_star regret measured_ce
                        (one row per sweep x grid offset 0..9 at spacing 10; the report's six-scan arm)
  k2_folds.tsv          held_out_protein k2_every_protein_once k2_all_in

Second mode (Task 6): --cut-sweeps <spectra_dir> <corpus Full_Scans dir> <out_dir> -- see cut_sweeps() below.
"""
import io, os, sys, datetime, glob, re
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pipeline as P              # noqa: E402  (vendored, verbatim)
import curve_families as CF       # noqa: E402  (vendored, verbatim)

D_SPARSE = 10                     # the report's six-scan arm: spacing 10 from CE 1 + offset, top edge always
CORPUS_COMMIT = "eed88d7"
GENERATOR = "FlashIDA/test-scripts/kinetic/make_kinetic_tables.py"


def fmt(v):
    if v is None:
        return ""
    if isinstance(v, (float, np.floating)):
        return "" if not np.isfinite(v) else "%.10g" % float(v)
    return str(v)


def header(source):
    stamp = datetime.date.today().isoformat()
    return ("# generated by %s on %s from %s (corpus %s); pipeline.py/curve_families.py vendored verbatim\n"
            % (GENERATOR, stamp, source, CORPUS_COMMIT))


def k2_folds(C):
    """k2 per leave-one-protein-out round, every protein counted once (regret_boxes_three_arms.py:72-77)."""
    prot = np.array([c["prot"] for c in C]); prots = sorted(set(prot))
    k2_own = np.array([P.fit_ext(c["feed_full"], c["Y"], c["max_ce"])[0] for c in C])
    k2_prot = {q: float(np.median(np.log(k2_own[prot == q]))) for q in prots}
    fold = {p: float(np.exp(np.median([k2_prot[q] for q in prots if q != p]))) for p in prots}
    k2_all = float(np.exp(np.median(list(k2_prot.values()))))
    return fold, k2_all


def main(table, out_dir):
    P.SRC = table                                   # the vendored module hard-codes its path; point it at the argument
    C = P.load_curves()
    assert len(C) == 108, len(C)
    fold, k2_all = k2_folds(C)
    assert abs(min(fold.values()) - 0.036363) < 1e-6 and abs(max(fold.values()) - 0.039046) < 1e-6, fold
    assert abs(k2_all - 0.0388) < 1e-4, k2_all
    hdr = header(os.path.basename(table))
    os.makedirs(out_dir, exist_ok=True)

    with io.open(os.path.join(out_dir, "sweep_shares.tsv"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(hdr); fh.write("# protein\tdataset\tcharge\tsweep\tce\tprecursor_share\treading\n")
        for c in C:
            for i, ce in enumerate(c["ce"]):
                fh.write("\t".join([c["prot"], c["key"][0], c["key"][1], c["key"][2], str(int(ce)),
                                    fmt(float(c["share"][i])), fmt(float(c["read"][i]))]) + "\n")

    regrets = []
    with io.open(os.path.join(out_dir, "kinetic_expected.tsv"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(hdr)
        fh.write("# protein\tdataset\tcharge\tsweep\toffset\tn_points\tp0\tce_max_s\twidth\tsse\tk2\tce_star\tregret\tmeasured_ce\n")
        for c in C:
            xu = c["ce"].astype(float); k2 = fold[c["prot"]]
            measured = int(np.nanargmax(c["read"])) + 1
            for off in range(D_SPARSE):
                sel = P.acquired(c, D_SPARSE, off)
                ce_a, sh_a = xu[sel], c["share"][sel]
                n = int(np.isfinite(sh_a).sum())
                par = CF.fit("Gompertz", ce_a, sh_a, A_max=CF.plateau_bound(sh_a)) if n >= 3 else None
                if par is None:
                    row = [c["prot"], c["key"][0], c["key"][1], c["key"][2], off, n, "", "", "", "", fmt(k2), 0, "", measured]
                else:
                    s = CF.feed_of("Gompertz", par, xu)
                    sc = P.score(s, c, k2)
                    regrets.append(sc["regret"])
                    row = [c["prot"], c["key"][0], c["key"][1], c["key"][2], off, n,
                           fmt(par[0]), fmt(par[1]), fmt(par[2]), fmt(par[3]), fmt(k2), sc["pick"], fmt(sc["regret"]), measured]
                fh.write("\t".join(str(v) for v in row) + "\n")

    with io.open(os.path.join(out_dir, "k2_folds.tsv"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(hdr); fh.write("# held_out_protein\tk2_every_protein_once\tk2_all_in\n")
        for p in sorted(fold):
            fh.write("%s\t%.6f\t%.6f\n" % (p, fold[p], k2_all))

    print("sweeps %d, fits %d, mean regret (six-scan arm, all offsets) %.4f, k2 folds %.6f-%.6f, all-in %.4f"
          % (len(C), len(regrets), float(np.mean(regrets)), min(fold.values()), max(fold.values()), k2_all))


# ---------------------------------------------------------------------------------------------- Task 6
def read_fixture(path):
    """FlashIDA spectrum fixture: 'Spec scan=N\\t<rt>' then 'mz\\tintensity' per line."""
    mz, it = [], []
    with io.open(path, encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            a, b = line.split("\t")[:2]
            mz.append(float(a)); it.append(float(b))
    return np.array(mz), np.array(it)


def cut_sweeps(spectra_dir, full_scans_dir, out_dir, k2_table):
    """Expectations for the three cut sweeps on CENTROIDED shares: the engine reads the fixture peaks, the study read
    profile arrays, so layer B compares the engine with the pipeline on the same input. The window is the one the
    corpus run's own engine commanded (scan_commands.tsv of that run: precursor_mz +- isolation_width/2 of the
    exploration rows of that charge)."""
    SETS = [  # (set, protein, charge, fixture prefix, run dir glob, expected-table protein key, sweep)
        ("cytc_z17", "Cytc", 17, "ms2_cytc_z17_ce", "*Cytc*2026-09-06-03-24-59", "1"),
        ("ubq_z9", "Ubiquitin", 9, "ms2_ubq_z9_ce", "*Ubiquitin*2026-09-04-18-23-55", "1"),
        ("tryg_z12", "Trypsinogen", 12, "ms2_tryg_z12_ce", "*Trypsinogen_90min_150nlmin_12ul_2026-09-04-14-28-54", "1"),
    ]
    folds = {}
    with io.open(k2_table, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"): continue
            p, k, _ = line.rstrip("\n").split("\t"); folds[p] = float(k)
    profile = {}
    with io.open(os.path.join(out_dir, "kinetic_expected.tsv"), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"): continue
            c = line.rstrip("\n").split("\t")
            if c[4] == "0": profile[(c[0], c[2], c[3])] = int(c[11])
    rows = []
    for set_name, prot, z, prefix, run_glob, sweep in SETS:
        run_dir = glob.glob(os.path.join(full_scans_dir, run_glob))
        assert len(run_dir) == 1, (run_glob, run_dir)
        windows = set()
        with io.open(os.path.join(run_dir[0], "scan_commands.tsv"), encoding="utf-8") as fh:
            hdr = fh.readline().rstrip("\n").split("\t"); H = {h: i for i, h in enumerate(hdr)}
            for line in fh:
                c = line.rstrip("\n").split("\t")
                if c[H["scan_type"]] == "exploration" and c[H["ms_level"]] == "2" and c[H["charge"]] == str(z):
                    windows.add((round(float(c[H["precursor_mz"]]), 4), round(float(c[H["isolation_width"]]), 4)))
        assert len(windows) == 1, (set_name, windows)
        (pmz, w), = windows
        lo, hi = pmz - w / 2.0, pmz + w / 2.0
        shares = {}
        for path in glob.glob(os.path.join(spectra_dir, prefix + "*.txt")):
            m = re.search(r"ce(\d+)\.txt$", os.path.basename(path))
            if not m: continue
            mz, it = read_fixture(path)
            tot = it.sum()
            shares[int(m.group(1))] = float(it[(mz >= lo) & (mz <= hi)].sum() / tot) if tot > 0 else np.nan
        grid = [1, 11, 21, 31, 41, 50]
        assert all(g in shares for g in grid), (set_name, sorted(shares))
        ce_a = np.array(grid, float); sh_a = np.array([shares[g] for g in grid])
        par = CF.fit("Gompertz", ce_a, sh_a, A_max=CF.plateau_bound(sh_a))
        xu = np.arange(1, 51, dtype=float)
        s = CF.feed_of("Gompertz", par, xu)
        B = P.direct(s, folds[prot], 50)
        ce_star = int(np.argmax(B)) + 1
        ce_prof = profile[(prot, str(z), sweep)]
        rows.append([set_name, prot, z, "%.4f" % lo, "%.4f" % hi, fmt(folds[prot]), int(np.isfinite(sh_a).sum()),
                     fmt(par[0]), fmt(par[1]), fmt(par[2]), ce_star, ce_prof] + [fmt(shares[g]) for g in grid])
        print("%s: centroid CE* %d, profile CE* %d (gap %d)" % (set_name, ce_star, ce_prof, abs(ce_star - ce_prof)))
        assert abs(ce_star - ce_prof) <= 3, "centroided share does not carry the curve on %s" % set_name
    with io.open(os.path.join(out_dir, "cut_sweep_expected.tsv"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header("the cut fixtures under test-data/spectra + the corpus runs' scan_commands.tsv windows"))
        fh.write("# set\tprotein\tcharge\tmz_lo\tmz_hi\tk2\tn_points\tp0\tce_max_s\twidth\tce_star_centroid\tce_star_profile"
                 "\tshare_1\tshare_11\tshare_21\tshare_31\tshare_41\tshare_50\n")
        for r in rows:
            fh.write("\t".join(str(v) for v in r) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "--cut-sweeps":
        cut_sweeps(sys.argv[2], sys.argv[3], sys.argv[4], os.path.join(sys.argv[4], "k2_folds.tsv"))
    else:
        main(sys.argv[1], sys.argv[2])
